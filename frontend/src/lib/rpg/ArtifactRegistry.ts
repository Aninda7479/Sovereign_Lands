export const RPG_ITEMS_BY_ID: Record<string, RPGItem> = ALL_RPG_ITEMS.reduce(
  (acc, item) => {
    acc[item.id] = item;
    return acc;
  },
  {} as Record<string, RPGItem>
);

export function getItemById(id: string): RPGItem | undefined {
  return RPG_ITEMS_BY_ID[id];
}

export function getItemsByCategory(category: ItemCategory): RPGItem[] {
  return ALL_RPG_ITEMS.filter((item) => item.category === category);
}

export function getItemsByRarity(rarity: ItemRarity): RPGItem[] {
  return ALL_RPG_ITEMS.filter((item) => item.rarity === rarity);
}
